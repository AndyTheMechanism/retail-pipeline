-- Недельный фон выручки: скользящее среднее за 7 дней.
--
-- Живет отдельной моделью, а не колонкой в витрине продаж, и причина
-- практическая. Витрина продаж инкрементальная и пересобирается по окну дат;
-- скользящее окно в семь дней перетягивает соседние строки, и пересчет одного
-- дня начал бы менять семь. Развязка стоит одного джойна в дашборде и снимает
-- необходимость это объяснять: сама модель тренда собирается целиком, и на 62
-- тысячах строк полная пересборка дешевая.

with sales as (
    select
        store_id,
        order_date,
        revenue_net
    from {{ ref('mart_store_daily_sales') }}
)

select
    store_id,
    order_date,
    revenue_net,

    -- Среднее не выдается, если в окне есть день без данных. avg молча
    -- пропустил бы null и поделил на меньшее число дней - то есть подменил бы
    -- пропуск оценкой, а это ровно то, чего проект не делает. Неполное окно
    -- честнее оставить пустым.
    case when count(revenue_net) over w = 7
         then avg(revenue_net) over w
    end as revenue_net_avg_7d

from sales

window w as (
    -- rows, а не range: считаем ровно семь строк подряд, и это корректно
    -- только потому, что ось плотная - ее дает спайн. На разреженной оси
    -- rows брал бы семь строк, между которыми могут лежать месяцы.
    partition by store_id
    order by order_date
    rows between 6 preceding and current row
)
