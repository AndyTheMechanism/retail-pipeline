-- Сборка чека: позиция заказа вместе с его шапкой.
--
-- Тот самый тяжелый джойн, 3,57 млн строк на 1,49 млн. Материализуется
-- таблицей, чтобы сортировка дедупликации и этот джойн выполнились один раз, а
-- не заново на каждый запрос к витрине и на каждый тест этапа 3.
--
-- Джойн левый намеренно. Внутренний молча выбросил бы позицию, у которой нет
-- заказа, и тесту на ссылочную целостность на этапе 3 нечего было бы ловить.
-- Здесь такая позиция остается со store_id = null и видна запросом; решение,
-- что с ней делать, принимает витрина, а не промежуточный слой.
--
-- order_date берется из позиции, а не из шапки: в сыром слое он денормализован
-- как ключ партиции и есть даже у осиротевшей строки. Совпадение двух дат -
-- инвариант, и проверяется он тестом на этапе 3, а не навязывается джойном:
-- джойн по обеим датам спрятал бы расхождение как отсутствующую строку.

with lines as (
    select * from {{ ref('stg_order_items') }}
),

orders as (
    select * from {{ ref('stg_orders') }}
)

select
    l.order_id,
    l.line_no,
    l.order_date,

    o.store_id,
    o.channel,
    o.is_cancelled,
    o.is_offline,

    l.sku,
    l.quantity,
    l.unit_price,
    l.line_amount,
    l.source_copies

from lines l
left join orders o on o.order_id = l.order_id
