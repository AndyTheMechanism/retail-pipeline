-- Позиции заказа, по одной строке на позицию.
--
-- Единственное место, где восстанавливается зерно (order_id, line_no). В сыром
-- слое лежат дубли выгрузки, и без этой модели они дошли бы до витрины
-- задвоенной выручкой.
--
-- Почему row_number, а не distinct. Distinct убирает только точные копии и
-- молча оставляет две строки на одну позицию, если копии разошлись, - а
-- разойтись они могут: выбросы накладываются на список, уже содержащий дубли,
-- и портят одну копию, не трогая вторую. Row_number заявляет зерно, а не
-- борется с симптомом. Заодно он дает source_copies - сколько строк было в
-- источнике на эту позицию: дедупликация должна быть проверяемым фактом, а не
-- подразумеваемой.
--
-- Почему сортировка в окне именно такая. Выбор между разошедшимися копиями
-- произволен по смыслу, поэтому обязан быть хотя бы воспроизводимым. Без
-- order by порядок строк внутри окна не определен вовсе, и два dbt run дали бы
-- разные числа - воспроизводимость сломалась бы молча, то есть самым
-- неприятным способом. Ctid не годится: он физический и меняется после
-- перезаливки партиции. Сортировка намеренно не пытается выбрать "правильную"
-- копию, например не-выброс: это была бы тихая починка данных, а чинить их
-- здесь нельзя - на них стоит гейт сверки собранного чека с сырьем,
-- tests/assert_order_lines_match_raw.sql.
--
-- Честная оговорка: на текущем сиде даты дублей и даты выбросов не
-- пересекаются, копии точные, и сортировка не меняет ни одного числа. Она
-- стоит страховкой от смены сида, а не чинит что-то сегодня.

with source as (
    select * from {{ source('raw', 'order_items') }}
),

numbered as (
    select
        order_id,
        order_date,
        line_no,
        sku,
        quantity,
        unit_price,
        line_amount,

        -- order_date в partition by стоит не для смысла, а ради плана запроса,
        -- и это единственное место в проекте, где форма выражения выбрана из-за
        -- оптимизатора. Причина: предикат не проваливается сквозь оконную
        -- функцию - планировщик обязан посчитать окно раньше, чем применит
        -- фильтр, - если только колонка фильтра не входит в partition by. Пока
        -- ее там не было, прогон за одну дату считал дедупликацию по всем
        -- 3,5 млн строк и выбрасывал 3 560 185 из них: 2,7 секунды вместо
        -- девяти миллисекунд. Замеры и планы - в QUERY-PLAN.md.
        --
        -- На результат это не влияет: order_date функционально зависит от
        -- order_id, потому что идентификатор заказа кодирует дату. Групп
        -- добавленная колонка не дробит, а если бы вдруг дробила - зерно
        -- (order_id, line_no) проверяется отдельным тестом, и он бы покраснел.
        count(*) over (partition by order_date, order_id, line_no) as source_copies,

        row_number() over (
            partition by order_date, order_id, line_no
            order by line_amount, quantity, unit_price, sku
        ) as copy_no

    from source
)

select
    order_id,
    order_date,
    line_no,
    sku,
    quantity,
    unit_price,
    line_amount,
    source_copies
from numbered
where copy_no = 1
