-- Возврат к отмененному заказу невозможен по смыслу.
--
-- Отмененный заказ не был выдан, возвращать нечего. Если такая строка
-- появится, это не редкий случай из жизни, а рассинхрон между источниками -
-- и выручка нетто уедет вниз на сумму, которой не было.
--
-- Ссылочная целостность возвратов проверяется отдельно, штатным relationships:
-- здесь речь не про отсутствующий заказ, а про существующий и неподходящий.

select
    return_id,
    order_id,
    store_id,
    order_date,
    returned_date,
    returned_amount
from {{ ref('int_returns_attributed') }}
where is_cancelled
