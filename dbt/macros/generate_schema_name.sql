{#
    Схемы называются так, как их назовет читатель.

    По умолчанию dbt склеивает целевую схему с объявленной и дает
    analytics_staging, analytics_marts. Здесь склейка убрана: модель уходит
    ровно в ту схему, которую объявил ее каталог, и запрос к витрине пишется
    как select * from marts.mart_store_daily_sales, а не с приставкой, которую
    надо помнить.

    Плату называю вслух, потому что склейка нужна не просто так: на общей базе
    двое разработчиков с разными целевыми схемами затерли бы друг друга. Здесь
    база локальная и одна на проект, так что платить нечем. Как только база
    станет общей, макрос придется убрать - и это тот случай, когда решение
    зависит от обстоятельств, а не от вкуса.
#}
